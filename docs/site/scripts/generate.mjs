// Files the site builds from the repository rather than keeping its own copies, so they can't
// drift: the config JSON Schema, published at the URL in its `$id`, and the configuration
// reference page, written from the schema's descriptions. Both outputs are gitignored.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const site = join(import.meta.dirname, "..");
const root = join(site, "..", "..");

const write = (path, text) => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
};

const typeOf = (node) => {
  if (node.enum) return node.enum.map((v) => `\`${JSON.stringify(v)}\``).join(", ");
  if (node.anyOf) return node.anyOf.map(typeOf).join(" or ");
  if (node.type === "array") return `${node.items ? typeOf(node.items) : "any"} list`;
  if (node.type === "object" && node.additionalProperties && !node.properties) {
    return `map of ${typeOf(node.additionalProperties)}`;
  }
  return node.type ?? "any";
};

/** One section per setting, depth first: top-level keys as `##`, nested ones as `###`. */
function sections(properties, prefix, out) {
  for (const [name, node] of Object.entries(properties)) {
    if (name === "$schema") continue;
    const key = `${prefix}${name}`;
    const leaf = node.type !== "object" || !node.properties;
    out.push(`${prefix ? "###" : "##"} \`${key}\``, "");
    if (leaf) {
      const fallback =
        node.default !== undefined ? ` Default: \`${JSON.stringify(node.default)}\`.` : "";
      out.push(`${node.enum ? "One of" : "Type:"} ${typeOf(node)}.${fallback}`, "");
    }
    if (node.description) out.push(node.description, "");
    if (!leaf) sections(node.properties, `${key}.`, out);
  }
  return out;
}

export function configReference(schema) {
  const lines = [
    "---",
    "title: Configuration reference",
    "description: Every key in switchkick's config file, generated from its JSON Schema.",
    "---",
    "",
    "<!-- Generated by docs/site/scripts/generate.mjs from schema/v1.json. Don't edit. -->",
    "",
    "switchkick reads `~/.config/switchkick/config.yaml`, or the file named by `--config` or",
    "`SWITCHKICK_CONFIG`. Every key is optional, and unknown keys are rejected so a typo doesn't go",
    "unnoticed. Command-line flags and `SWITCHKICK_*` variables override the file.",
    "",
    "For completion and checking in your editor, start the file with the schema line. The",
    `[schema](${schema.$id}) is generated from the same definitions switchkick validates with.`,
    "",
    "```yaml",
    `# yaml-language-server: $schema=${schema.$id}`,
    "mode: local",
    "```",
    "",
    ...sections(schema.properties, "", []),
  ];
  return lines.join("\n");
}

export function generate() {
  const text = readFileSync(join(root, "schema", "v1.json"), "utf8");
  const schema = JSON.parse(text);
  write(join(site, "public", "schema", "v1.json"), text);
  write(
    join(site, "src", "content", "docs", "reference", "configuration.md"),
    configReference(schema),
  );
}
