// Prints the Homebrew formula for a release, from the release's SHA256SUMS file. The release
// workflow commits it to the eased-tech/homebrew-switchkick tap as Formula/switchkick.rb.
//
//   node scripts/release/homebrew-formula.mjs 0.2.0 dist-bin/SHA256SUMS
import { readFileSync } from "node:fs";

const [version, sumsFile] = process.argv.slice(2);
if (!version || !sumsFile) {
  console.error("usage: node scripts/release/homebrew-formula.mjs <version> <SHA256SUMS>");
  process.exit(2);
}

const sums = new Map();
for (const line of readFileSync(sumsFile, "utf8").split("\n")) {
  const match = /^([0-9a-f]{64}) [ *]?(\S+)$/.exec(line.trim());
  if (match) sums.set(match[2], match[1]);
}

const base = `https://github.com/eased-tech/switchkick/releases/download/v${version}`;
const binary = (target) => {
  const file = `switchkick-${target}`;
  const sha = sums.get(file);
  if (!sha) {
    console.error(`${sumsFile} has no checksum for ${file}`);
    process.exit(1);
  }
  return `      url "${base}/${file}"\n      sha256 "${sha}"`;
};

process.stdout.write(`# Generated by scripts/release/homebrew-formula.mjs in eased-tech/switchkick. Don't edit.
class Switchkick < Formula
  desc "Proxy that routes OpenAI and Anthropic API traffic through OpenRouter"
  homepage "https://github.com/eased-tech/switchkick"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    on_arm do
${binary("darwin-arm64")}
    end
    on_intel do
${binary("darwin-x64")}
    end
  end

  on_linux do
    on_arm do
${binary("linux-arm64")}
    end
    on_intel do
${binary("linux-x64")}
    end
  end

  def install
    bin.install Dir["switchkick-*"].first => "switchkick"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/switchkick --version")
  end
end
`);
